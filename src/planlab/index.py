"""The operator's views: the status view and its two renderings.

The generated `README.md` and the text `status` output are the same data from
`status()`, rendered twice.

Rows link plan files with a RELATIVE markdown link, never a wikilink: a
dangling-link checker over the notes counts wikilinks, and a generated index
must not feed it.
"""

from __future__ import annotations

import datetime
import os
from collections.abc import Callable, Iterable
from typing import Any

from planlab import rules as R
from planlab import store as S

DRAFTS_SHOWN = 15
PRIORITY_ORDER = {"P0": 0, "P1": 1, "P2": 2, "P3": 3}
BANNER = "<!-- generated by planlab index — do not edit; your edits are overwritten -->"

Row = dict[str, Any]
View = dict[str, Any]


def as_date(value: object) -> datetime.date | None:
    if isinstance(value, datetime.datetime):
        return value.date()
    if isinstance(value, datetime.date):
        return value
    try:
        return datetime.date.fromisoformat(str(value)[:10])
    except (TypeError, ValueError):
        return None


def _pr_rows(p: S.Plan, pr_state: dict[str, Any]) -> list[Row]:
    return [
        {"number": n, "state": pr_state.get(str(n), {}).get("state", "unknown")}
        for n in p.list_of("prs")
    ]


def status(tree: str, show_all: bool = False) -> View:
    scanned = S.scan(tree)
    plans, problems = scanned
    index = S.by_id(plans)
    drifted = R.drift_blockers(plans)
    cache = R.sync_cache(tree)
    pr_state = cache.get("prs", {})
    v = R.validate(tree, scanned)
    hard = {e["id"] for e in v["errors"] if e["id"]}

    ready: list[Row] = []
    blocked: list[Row] = []
    in_flight: list[Row] = []
    orphans: list[Row] = []
    drafts: list[Row] = []
    hidden: list[tuple[datetime.date, Row]] = []
    for p in sorted(plans, key=lambda q: q.path):
        if p.error or not p.id:
            continue
        row: Row = {"id": p.id, "title": p.get("title"), "path": os.path.relpath(p.path, tree)}
        if p.state == "next":
            errs, unmet = R.dep_problems(p, index, drifted)
            if unmet:
                blocked.append(dict(row, blocked_by=unmet))
            elif not (errs or p.id in hard):
                ready.append(row)
        elif p.state == "open":
            in_flight.append(
                dict(
                    row,
                    claimed_by=p.get("claimed_by"),
                    branch=p.get("branch"),
                    prs=_pr_rows(p, pr_state),
                    stale_claim=R.stale_claim(p),
                )
            )
            if not p.get("claimed_by"):
                orphans.append(row)
        elif p.state == "drafts":
            when = as_date(p.get("revisit"))
            entry = dict(
                row,
                priority=p.get("priority"),
                date=str(p.get("date") or ""),
                revisit=str(p.get("revisit") or "") or None,
            )
            if when and when > datetime.date.today() and not show_all:
                hidden.append((when, entry))
            else:
                drafts.append(entry)

    drafts.sort(key=lambda d: (PRIORITY_ORDER.get(d.get("priority") or "", 9), d["date"], d["id"]))
    return {
        "tree": tree,
        "counts": {s: sum(1 for p in plans if p.state == s) for s in S.STATES},
        "ready": ready,
        "blocked": blocked,
        "in_flight": in_flight,
        "orphans": orphans,
        "drafts": drafts[:DRAFTS_SHOWN],
        "drafts_total": len(drafts) + len(hidden),
        "drafts_hidden": len(hidden),
        "drafts_next_revisit": str(min(h[0] for h in hidden)) if hidden else None,
        "done": [
            {
                "id": p.id,
                "title": p.get("title"),
                "verdict": p.get("verdict"),
                "verified": str(p.get("verified") or "") or None,
                "path": os.path.relpath(p.path, tree),
            }
            for p in sorted(
                (q for q in plans if q.state == "done" and q.id),
                key=lambda q: q.name,
                reverse=True,
            )
        ],
        "discarded": [
            {
                "id": p.id,
                "title": p.get("title"),
                "why": p.get("why"),
                "path": os.path.relpath(p.path, tree),
            }
            for p in sorted(
                (q for q in plans if q.state == "discarded" and q.id), key=lambda q: q.name
            )
        ],
        "problems": problems
        + [{"path": e.get("path"), "message": e["message"]} for e in v["errors"]],
        "warnings": v["warnings"],
        "error_count": len(v["errors"]),
        "synced_at": cache.get("synced_at"),
    }


# ── README.md ─────────────────────────────────────────────────────────────


def _link(row: Row) -> str:
    return f"[{row['id']}]({row['path']})"


def _title(row: Row) -> str:
    return _plain(row.get("title") or row["id"])


def _plain(text: object) -> str:
    """Neutralise wikilink and table syntax coming from plan frontmatter.

    A plan titled `[[something]]` would otherwise put a wikilink into the
    generated index — the exact thing this module exists to keep out of a
    dangling-link checker.
    """
    return str(text).replace("[[", "[ [").replace("]]", "] ]").replace("|", "\\|")


def _prs(row: Row) -> str:
    return ", ".join(f"#{p['number']} {p['state']}" for p in row["prs"]) or "no PR"


def _blockers(row: Row) -> str:
    return ", ".join(f"{b['id']} ({b['state']})" for b in row["blocked_by"])


def _counts(view: View) -> str:
    counts = view["counts"]
    return " · ".join(f"{s} {counts.get(s, 0)}" for s in S.STATES)


def _section(
    out: list[str],
    heading: str,
    rows: Iterable[Row],
    render_row: Callable[[Row], str],
    empty: str = "_none_",
) -> None:
    rows = list(rows)
    out.append(f"## {heading}")
    out.append("")
    if not rows:
        out.append(empty)
    else:
        out.extend(render_row(r) for r in rows)
    out.append("")


def _flight_line(r: Row) -> str:
    who = r.get("claimed_by") or "unclaimed"
    stale = " — STALE CLAIM" if r.get("stale_claim") else ""
    branch = r.get("branch") or "no branch"
    return f"- {_link(r)} — {_title(r)} — {who} on {branch} — {_prs(r)}{stale}"


def render_readme(view: View) -> str:
    name = view["tree"].rstrip("/").rsplit("/", 1)[-1]
    out = [BANNER, "", f"# Plan lifecycle — {name}", "", _counts(view), ""]

    _section(out, "Ready", view["ready"], lambda r: f"- {_link(r)} — {_title(r)}")
    _section(
        out,
        "Blocked",
        view["blocked"],
        lambda r: f"- {_link(r)} — {_title(r)} — blocked by {_blockers(r)}",
    )
    _section(out, "In flight", view["in_flight"], _flight_line)

    out.append("## Drafts")
    out.append("")
    if view["drafts"]:
        out.extend(
            f"- {r.get('priority') or '--'} {_link(r)} — {_title(r)}" for r in view["drafts"]
        )
    else:
        out.append("_none visible_")
    if view["drafts_total"] > len(view["drafts"]):
        out.append("")
        out.append(f"{len(view['drafts'])} of {view['drafts_total']} shown.")
    if view["drafts_hidden"]:
        out.append(
            f"{view['drafts_hidden']} hidden until their revisit date; "
            f"next is {view['drafts_next_revisit']}."
        )
    out.append("")

    _section(
        out,
        "Done",
        view["done"][:10],
        lambda r: f"- {_link(r)} — {_title(r)} — {_plain(r.get('verdict') or 'not verified')}",
    )
    _section(
        out,
        "Discarded",
        view["discarded"],
        lambda r: f"- {_link(r)} — {_title(r)} — {_plain(r.get('why') or 'no reason recorded')}",
    )
    _section(
        out, "Problems", view["problems"], lambda r: f"- {r.get('path') or '-'} — {r['message']}"
    )
    return "\n".join(out).rstrip("\n") + "\n"


def write_readme(tree: str, view: View) -> str:
    path = os.path.join(tree, "README.md")
    S.write_atomic(path, render_readme(view))
    return path


# ── text status ───────────────────────────────────────────────────────────


def render_status(view: View) -> str:
    """The text `planlab status` prints. Same data, terser."""
    out = [f"{view['tree']}  ({_counts(view)})"]
    if view.get("synced_at"):
        out.append(f"last sync: {view['synced_at']}")
    out.append("")

    def block(label: str, rows: list[Row], fmt: Callable[[Row], str]) -> None:
        out.append(f"{label} ({len(rows)})")
        if rows:
            out.extend("  " + fmt(r) for r in rows)
        else:
            out.append("  —")
        out.append("")

    block("READY", view["ready"], lambda r: f"{r['id']:<32} {_title(r)}")
    block("BLOCKED", view["blocked"], lambda r: f"{r['id']:<32} blocked by {_blockers(r)}")
    block(
        "IN FLIGHT",
        view["in_flight"],
        lambda r: (
            f"{r['id']:<32} {r.get('claimed_by') or 'unclaimed'}  {r.get('branch') or '-'}  "
            f"{_prs(r)}{'  STALE' if r.get('stale_claim') else ''}"
        ),
    )
    if view["orphans"]:
        block(
            "ORPHANS (open/ with no claimed_by)",
            view["orphans"],
            lambda r: f"{r['id']:<32} {_title(r)}",
        )
    block(
        "DRAFTS",
        view["drafts"],
        lambda r: f"{r.get('priority') or '--':<4} {r['id']:<32} {_title(r)}",
    )
    if view["drafts_total"] > len(view["drafts"]):
        hidden = (
            f"; {view['drafts_hidden']} hidden until {view['drafts_next_revisit']}"
            if view["drafts_hidden"]
            else ""
        )
        out[-1] = f"  {len(view['drafts'])} of {view['drafts_total']} shown{hidden}"
        out.append("")
    block("PROBLEMS", view["problems"], lambda r: f"{r.get('path') or '-':<32} {r['message']}")
    if view["warnings"]:
        block("WARNINGS", view["warnings"], lambda r: f"{r.get('id') or '-':<32} {r['message']}")
    return "\n".join(out).rstrip("\n") + "\n"
