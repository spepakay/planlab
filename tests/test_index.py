"""The status view and its two renderings: the JSON view and the generated README."""

from __future__ import annotations

import os
import time
from collections.abc import Callable

from support import Tree, slurp

Plan = Callable[..., str]


def readme(tree: Tree) -> str:
    return slurp(os.path.join(tree.path, "README.md"))


class TestStatus:
    def test_revisit_past_future_and_unparseable(self, tree: Tree, plan: Plan) -> None:
        plan("drafts", "past", revisit="2020-01-01")
        plan("drafts", "future", revisit="2099-01-01")
        plan("drafts", "junk", revisit="next quick-win pass")
        plan("drafts", "unset")
        s = tree.status_json()
        visible = [d["id"] for d in s["drafts"]]
        assert {"past", "unset", "junk"} <= set(visible)
        assert "future" not in visible
        assert s["drafts_hidden"] == 1
        assert s["drafts_next_revisit"] == "2099-01-01"
        assert "future" in [d["id"] for d in tree.status_json("--all")["drafts"]]

    def test_drafts_are_grouped_by_priority_and_capped_at_fifteen(
        self, tree: Tree, plan: Plan
    ) -> None:
        for i in range(20):
            plan("drafts", f"d{i:02d}", priority=f"P{i % 4}")
        s = tree.status_json()
        assert len(s["drafts"]) == 15
        assert s["drafts_total"] == 20
        assert [d["priority"] for d in s["drafts"]][:5] == ["P0"] * 5

    def test_a_timezone_aware_claimed_at_does_not_crash(self, tree: Tree, plan: Plan) -> None:
        # An ordinary unquoted `...Z` parses to a tz-AWARE datetime; subtracting
        # it from a naive now() used to raise TypeError and kill status.
        plan("open", "zulu", claimed_by="s", claimed_at="2020-01-01T00:00:00Z")
        row = next(r for r in tree.status_json()["in_flight"] if r["id"] == "zulu")
        assert row["stale_claim"]

    def test_two_hidden_drafts_sharing_a_revisit_date_do_not_crash(
        self, tree: Tree, plan: Plan
    ) -> None:
        plan("drafts", "one", revisit="2099-01-01")
        plan("drafts", "two", revisit="2099-01-01")
        s = tree.status_json()
        assert s["drafts_hidden"] == 2
        assert s["drafts_next_revisit"] == "2099-01-01"

    def test_stale_claim_is_flagged(self, tree: Tree, plan: Plan) -> None:
        stamp = "%Y-%m-%dT%H:%M:%S"
        old = time.strftime(stamp, time.gmtime(time.time() - 30 * 3600))
        plan("open", "slow", claimed_by="worker-a", claimed_at=old)
        plan("open", "fresh", claimed_by="worker-a", claimed_at=time.strftime(stamp, time.gmtime()))
        flags = {r["id"]: r.get("stale_claim") for r in tree.status_json()["in_flight"]}
        assert flags["slow"]
        assert not flags["fresh"]

    def test_blocked_names_the_blocking_ids_and_their_state(self, tree: Tree, plan: Plan) -> None:
        plan("next", "dep", date="2026-08-01")
        plan("next", "a", depends_on=["dep"])
        blocked = {r["id"]: r for r in tree.status_json()["blocked"]}
        assert blocked["a"]["blocked_by"] == [{"id": "dep", "state": "next"}]


class TestIndex:
    def test_golden_sections_and_relative_links(self, tree: Tree, plan: Plan) -> None:
        plan("next", "ready-one")
        plan("open", "flying", claimed_by="worker-a", branch="feat/flying", prs=[1])
        plan("done", "shipped", verdict="clean")
        plan("discarded", "dropped", why="superseded by shipped")
        plan("drafts", "idea", priority="P1")
        rc, _, err = tree.run("index", by="t")
        assert rc == 0, err
        text = readme(tree)
        for heading in (
            "## Ready",
            "## Blocked",
            "## In flight",
            "## Drafts",
            "## Done",
            "## Discarded",
            "## Problems",
        ):
            assert heading in text
        assert "generated by" in text.splitlines()[0]
        assert "(next/2026-09-01-ready-one.md)" in text
        assert "[[" not in text

    def test_a_wikilink_in_a_title_never_reaches_the_generated_index(
        self, tree: Tree, plan: Plan
    ) -> None:
        plan("next", "linky", title="See [[other/plan]] first")
        tree.run("index", by="t")
        text = readme(tree)
        assert "[[" not in text
        assert "other/plan" in text

    def test_running_index_twice_is_byte_identical(self, tree: Tree, plan: Plan) -> None:
        plan("next", "a")
        tree.run("index", by="t")
        first = readme(tree)
        tree.run("index", by="t")
        assert readme(tree) == first

    def test_hidden_draft_count_shows_the_next_revisit_date(self, tree: Tree, plan: Plan) -> None:
        plan("drafts", "later", revisit="2099-03-04")
        tree.run("index", by="t")
        text = readme(tree)
        assert "1 hidden" in text
        assert "2099-03-04" in text
